  // ── game ────────────────────────────────────────────────────────────────
  async function startRound(modeId) {
    const mode = modeOf(modeId);
    const st = store.settings;
    // A pack can be enabled from a previous session but not yet fetched.
    if ((st.packs || []).some((id) => DATA.packs[id]?.lazy && !loadedPacks.has(id))) {
      toast('Loading packs…', 8000);
      const ok = await ensurePacks(st.packs);
      $('#toast').hidden = true;
      if (!ok) return;
    }
    const p = eligible(pool(), mode);
    if (p.length < 4) {
      return toast(mode.needs === 'capital' ? 'Not enough flags with capitals in scope'
        : mode.needs === 'near' ? 'Not enough look-alike flags in scope'
        : 'Not enough flags in scope');
    }
    const n = mode.adaptive ? Math.min(st.length, p.length) : st.length;
    const qs = pickQuestions(p, n, mode.adaptive ? 'training' : 'quick');
    if (qs.length < 1) return toast('Not enough flags in scope');

    session = {
      mode: mode.id, pool: p, qs, i: 0, distinct: distinctCounts(p),
      correct: 0, streak: 0, bestStreak: 0, score: 0,
      misses: [], times: [], newlyMastered: [],
      t0: Date.now(), locked: false,
    };
    show('game');
    renderQuestion();
  }

  // What the buttons say for a given option, per question kind.
  function optionLabel(o, kind) {
    const spec = KINDS[kind];
    return String(FACTS[spec.fact || 'name'](o) ?? o.name);
  }

  function renderQuestion() {
    const s = session;
    const f = s.qs[s.i];
    const st = store.settings;
    const mode = modeOf(s.mode);
    // Mixed modes draw a kind per question from whatever is switched on, falling
    // back to naming the flag when this particular flag cannot support the rest.
    let kind;
    if (mode.mix) {
      const wanted = (st.kinds && st.kinds.length ? st.kinds : ['flag-name']);
      const usable = wanted.filter((k) => kindUsable(k, f, s.pool, s.distinct));
      kind = usable.length ? usable[(Math.random() * usable.length) | 0] : 'flag-name';
    } else {
      kind = (mode.flip && st.reverse) ? mode.flip : mode.kind;
    }
    const spec = KINDS[kind];
    s.kind = kind;
    s.locked = false;
    s.qStart = Date.now();

    $('#qCount').textContent = `${s.i + 1}/${s.qs.length}`;
    $('#qProgFill').style.width = `${(s.i / s.qs.length) * 100}%`;

    const sb = $('#streakBadge');
    if (s.streak >= 3) {
      sb.hidden = false;
      sb.textContent = `${s.streak} in a row`;
      sb.classList.remove('bump'); void sb.offsetWidth; sb.classList.add('bump');
    } else {
      sb.hidden = true;
    }

    // Held on the session: a timeout grades the question with no click to
    // report, and still needs the options to mark up the right answer.
    const built = buildQuestion(f, s.pool, mode, kind);
    const opts = built.options;
    s.opts = opts;
    s.correctCode = built.correctCode;

    const card = $('#flagCard');
    const nameEl = $('#promptName');
    const askEl = $('#askLine');
    const box = $('#answers');
    box.innerHTML = '';

    // ── prompt ──
    card.hidden = spec.prompt !== 'flag' && spec.prompt !== 'zoom';
    nameEl.hidden = spec.prompt !== 'fact';

    if (spec.prompt === 'flag') {
      card.innerHTML = flagMarkup(f.code);
    } else if (spec.prompt === 'zoom') {
      // Start hard in on a random detail and pull back over the question.
      // Origin is kept near the middle and the opening scale modest: a deep zoom
      // into the corner of a plain stripe shows a blank rectangle, which is not
      // a question. Easing opens it quickly, then settles, so a uniform first
      // frame resolves fast and answering early is still worth real points.
      const zx = 35 + Math.random() * 30;
      const zy = 35 + Math.random() * 30;
      card.innerHTML = `<div class="zoomer">${flagMarkup(f.code)}</div>`;
      const z = card.firstElementChild;
      z.style.setProperty('--zx', zx.toFixed(1) + '%');
      z.style.setProperty('--zy', zy.toFixed(1) + '%');
      z.style.animation = `zoomOut ${QUESTION_MS}ms cubic-bezier(.3,.85,.4,1) forwards`;
    } else {
      nameEl.innerHTML = '';
      if (spec.ask) {
        const small = document.createElement('small');
        small.textContent = spec.ask;
        nameEl.appendChild(small);
      }
      nameEl.appendChild(document.createTextNode(
        String(FACTS[spec.promptFact || 'name'](f) ?? f.name)));
    }

    // A line stating the question where the prompt alone does not imply it.
    const showAsk = spec.ask && spec.prompt === 'flag';
    askEl.hidden = !showAsk;
    if (showAsk) askEl.textContent = spec.ask;

    // ── options ──
    for (const o of opts) {
      const b = document.createElement('button');
      if (spec.option === 'flag') {
        b.className = 'ans flagged';
        b.innerHTML = flagMarkup(o.code);
        b.setAttribute('aria-label', o.name);
      } else {
        b.className = 'ans';
        b.textContent = optionLabel(o, kind);
      }
      b.onclick = () => answer(o);
      box.appendChild(b);
    }

    if (mode.timed) {
      startTimer();
    } else {
      $('#timer').hidden = true;
      $('#timeBar').hidden = true;
    }
  }

  function startTimer() {
    stopTimer();
    const el = $('#timer');
    const bar = $('#timeBar');
    const fill = $('#timeBarFill');
    const view = $('#view-game');
    el.hidden = false;
    bar.hidden = false;

    // Restart the drain. Clearing the animation and forcing a reflow is what
    // makes it replay on the next question rather than staying finished.
    fill.style.animation = 'none';
    void fill.offsetWidth;
    fill.style.animation = `drain ${QUESTION_MS}ms linear forwards`;
    fill.style.animationPlayState = 'running';

    const end = session.qStart + QUESTION_MS;
    const tick = () => {
      const left = Math.max(0, end - Date.now());
      const elapsed = QUESTION_MS - left;
      el.textContent = (left / 1000).toFixed(1) + 's';
      el.classList.toggle('low', left <= URGENT_MS);
      view.classList.toggle('warn', elapsed >= WARN_AFTER_MS && left > URGENT_MS);
      view.classList.toggle('urgent', left <= URGENT_MS && left > 0);
      if (left <= 0) { stopTimer(); if (!session.locked) answer(null); }
    };
    tick();
    tickHandle = setInterval(tick, 100);
  }

  function stopTimer() {
    if (tickHandle) { clearInterval(tickHandle); tickHandle = null; }
    // Freeze rather than reset, so the bar still shows what was left on the clock.
    const fill = $('#timeBarFill');
    if (fill) fill.style.animationPlayState = 'paused';
    $('#view-game')?.classList.remove('warn', 'urgent');
  }

  const kindOfSession = () => (session && session.kind) || 'flag-name';

  function answer(choice) {
    const s = session;
    if (!s || s.locked) return;
    s.locked = true;
    stopTimer();
    $('#timer').hidden = true; // a frozen countdown reads as still running
    const z = document.querySelector('#flagCard .zoomer');
    if (z) { z.style.animation = 'none'; z.style.transform = 'scale(1)'; }

    const f = s.qs[s.i];
    const ms = Date.now() - s.qStart;
    // For Borders the answer is a neighbour, not the flag on screen — so the
    // question records which code is correct rather than assuming it.
    const right = !!choice && choice.code === (s.correctCode || f.code);
    s.times.push(ms);

    // grade + schedule
    const r = rec(f.code);
    const wasBox = r.box;
    r.n++; r.last = Date.now();
    if (right) {
      r.c++; r.streak++;
      r.box = Math.min(INTERVALS.length - 1, r.box + 1);
      s.correct++; s.streak++;
      s.bestStreak = Math.max(s.bestStreak, s.streak);
      // Any timed mode scores. This was pinned to the literal 'quick' from before
      // the other modes existed, so Capitals, Lookalikes and Zoom banked nothing
      // while the results screen still showed a score — which was always zero.
      if (modeOf(s.mode).timed) {
        const speed = Math.max(0, 1 - ms / QUESTION_MS);
        s.score += 100 + Math.round(100 * speed) + Math.max(0, s.streak - 2) * 10;
      }
      if (wasBox < MASTERED_BOX && r.box >= MASTERED_BOX) s.newlyMastered.push(f.code);
    } else {
      r.streak = 0;
      r.box = Math.max(0, r.box - 2);
      s.streak = 0;
      s.misses.push({ code: f.code, chose: choice ? choice.code : null });
    }
    r.due = Date.now() + INTERVALS[r.box];
    saveStore();
    buzz(right ? 18 : [26, 50, 26]);
    if (right) { SFX.correct(s.streak); flash('good'); }
    else { SFX.wrong(); flash('bad'); }

    // feedback
    const opts = s.opts;
    const buttons = [...$('#answers').children];
    buttons.forEach((b, idx) => {
      b.disabled = true;
      const o = opts[idx];
      if (o.code === (s.correctCode || f.code)) b.classList.add('correct');
      else if (choice && o.code === choice.code) b.classList.add('wrong');
      else b.classList.add('muted');
    });

    const delay = right ? 420 : 1250;   // correct answers move on fast
    if (store.settings.auto) setTimeout(next, delay);
    else {
      const cont = document.createElement('button');
      cont.className = 'ans';
      cont.style.gridColumn = '1 / -1';
      const answerLabel = optionLabel(BY.get(s.correctCode || f.code) || f, kindOfSession());
      cont.textContent = right ? 'Next' : `${answerLabel} — Next`;
      cont.disabled = false;
      cont.onclick = next;
      $('#answers').appendChild(cont);
    }
  }

  function next() {
    const s = session;
    if (!s) return;
    s.i++;
    if (s.i >= s.qs.length) finishRound();
    else renderQuestion();
  }

  function finishRound() {
    const s = session;
    stopTimer();
    const entry = {
      t: Date.now(), mode: s.mode, n: s.qs.length, c: s.correct,
      score: s.score, bestStreak: s.bestStreak,
      ms: s.times.reduce((a, b) => a + b, 0),
      misses: s.misses.map((m) => m.code),
    };
    SFX.finish();
    store.sessions.push(entry);
    if (store.sessions.length > 300) store.sessions = store.sessions.slice(-300);
    saveStore();
    renderResults(entry);
    show('results');
  }

