  // ── question selection ──────────────────────────────────────────────────
  function pickQuestions(p, n, mode) {
    if (p.length === 0) return [];
    if (mode === 'quick') return shuffle(p.slice()).slice(0, Math.min(n, p.length));

    // Training: due items first (most overdue first), then never-seen,
    // then the ones being got wrong most often.
    const now = Date.now();
    const due = [], fresh = [], rest = [];
    for (const f of p) {
      const r = store.flags[f.code];
      if (!r || r.n === 0) { fresh.push(f); continue; }
      if (r.due <= now) due.push(f); else rest.push(f);
    }
    due.sort((a, b) => store.flags[a.code].due - store.flags[b.code].due);
    shuffle(fresh);
    rest.sort((a, b) => {
      const ra = store.flags[a.code], rb = store.flags[b.code];
      return (ra.c / ra.n) - (rb.c / rb.n);
    });
    return [...due, ...fresh, ...rest].slice(0, Math.min(n, p.length));
  }

  // How alike two flags are — drives the wrong answers.
  function similarity(a, b) {
    let s = 0;
    if (a.near && a.near.includes(b.code)) s += 100;
    if (a.subregion && a.subregion === b.subregion) s += 40;
    else if (a.region && a.region === b.region) s += 15;
    const setB = new Set(b.colours);
    let shared = 0;
    for (const c of a.colours) if (setB.has(c)) shared++;
    const union = new Set([...a.colours, ...setB]).size;
    if (union) s += (shared / union) * 35;
    return s;
  }

  // Two flags that are indistinguishable as drawn must never share a question —
  // that is not a hard question, it is one with two right-looking answers.
  const clashes = (a, b) =>
    (a.clash && a.clash.includes(b.code)) || (b.clash && b.clash.includes(a.code));

  // Take the first n candidates that clash neither with the answer nor with
  // anything already picked.
  function takeCompatible(answer, candidates, n) {
    const picked = [];
    for (const c of candidates) {
      if (picked.length >= n) break;
      if (clashes(answer, c)) continue;
      if (picked.some((x) => clashes(x, c))) continue;
      picked.push(c);
    }
    return picked;
  }

  function distractors(answer, p, hard) {
    const others = p.filter((f) => f.code !== answer.code && !clashes(answer, f));
    if (others.length <= 3) return shuffle(others.slice()).slice(0, 3);

    const scored = others
      .map((f) => ({ f, s: similarity(answer, f) + Math.random() * (hard ? 8 : 45) }))
      .sort((a, b) => b.s - a.s);

    // Hard mode takes the nearest look-alikes. Normal mode takes a couple of
    // plausible ones plus a wildcard, so it does not become a colour puzzle.
    if (hard) return takeCompatible(answer, scored.map((x) => x.f), 3);

    // Two plausible options plus a wildcard, so it does not become a pure
    // colour-matching puzzle. `fill` then tops the list back up to three from
    // everything remaining, so clash-filtering can never leave a short question.
    const near = scored.slice(0, Math.min(8, scored.length)).map((x) => x.f);
    const chosen = takeCompatible(answer, shuffle(near), 2);
    const fill = (candidates) => {
      for (const c of candidates) {
        if (chosen.length >= 3) return;
        if (chosen.some((x) => x.code === c.code)) continue;
        if (clashes(answer, c) || chosen.some((x) => clashes(x, c))) continue;
        chosen.push(c);
      }
    };
    fill(shuffle(others.slice()));
    return chosen.slice(0, 3);
  }

  // Lookalikes draws its wrong answers from the catalogued twins first, so the
  // whole round is made of flags you could genuinely confuse.
  function distractorsFor(f, p, mode) {
    if (mode.id !== 'lookalikes') {
      return distractors(f, p, mode.forceHard || store.settings.hard);
    }
    const byCode = new Map(p.map((x) => [x.code, x]));
    const twins = (f.near || []).map((c) => byCode.get(c)).filter(Boolean);
    const chosen = takeCompatible(f, shuffle(twins.slice()), 3);
    if (chosen.length < 3) {
      const have = new Set([f.code, ...chosen.map((x) => x.code)]);
      const ranked = p.filter((x) => !have.has(x.code))
        .map((x) => ({ x, s: similarity(f, x) }))
        .sort((a, b) => b.s - a.s)
        .map((o) => o.x)
        .filter((x) => !chosen.some((c) => clashes(c, x)));
      chosen.push(...takeCompatible(f, ranked, 3 - chosen.length));
    }
    return chosen;
  }

  // ── building a question ─────────────────────────────────────────────────
  // Returns the four options and which code is actually correct. For most kinds
  // that is the flag being shown; for Borders it is one of its neighbours.
  function buildQuestion(f, p, mode, kind) {
    const spec = KINDS[kind];

    if (spec.border) {
      // Keep the answer inside the current scope, so filtering to Europe does
      // not produce a European flag whose only correct answer is in Asia.
      const neigh = (f.borders || []).map((c) => BY.get(c))
        .filter((x) => x && p.some((q) => q.code === x.code));
      const correct = neigh[(Math.random() * neigh.length) | 0];
      const excluded = new Set([f.code, ...(f.borders || [])]);
      const others = shuffle(p.filter((x) => !excluded.has(x.code)));
      return { options: shuffle([correct, ...others.slice(0, 3)]), correctCode: correct.code };
    }

    const valueOf = FACTS[spec.fact];
    const want = valueOf(f);
    const seen = new Set([String(want)]);
    // Names get the similarity-ranked distractors; other facts just need three
    // options whose value genuinely differs, or the question has two right answers.
    const candidates = spec.fact === 'name'
      ? distractorsFor(f, p, mode)
      : shuffle(p.slice());
    const picked = [];
    for (const c of candidates) {
      if (picked.length >= 3) break;
      if (c.code === f.code) continue;
      const v = valueOf(c);
      if (v == null || seen.has(String(v))) continue;
      if (spec.fact === 'name' && (clashes(f, c) || picked.some((x) => clashes(x, c)))) continue;
      seen.add(String(v));
      picked.push(c);
    }
    return { options: shuffle([f, ...picked]), correctCode: f.code };
  }

  // Can this kind actually be asked about this flag, within this pool?
  function kindUsable(kind, f, p, distinct) {
    const spec = KINDS[kind];
    if (!spec) return false;
    if (spec.border) {
      const neigh = (f.borders || []).filter((c) => p.some((q) => q.code === c));
      return neigh.length > 0 && p.length >= 5;
    }
    const factName = spec.fact || spec.promptFact;
    if (FACTS[factName](f) == null) return false;
    // Need the answer plus three genuinely different values available.
    return (distinct[factName] || 0) >= 4;
  }

  // Distinct value counts for the pool, computed once per round.
  function distinctCounts(p) {
    const out = {};
    for (const key of Object.keys(FACTS)) {
      out[key] = new Set(p.map((f) => FACTS[key](f)).filter((v) => v != null)).size;
    }
    return out;
  }

